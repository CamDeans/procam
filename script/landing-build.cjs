#!/usr/bin/env node
/**
 * Builds and preps the landing page for deploy (e.g. procam.cloud).
 * Writes landing/dist/ with config.js set from LANDING_APP_URL env.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const landingDir = path.join(root, 'landing');
const outDir = path.join(landingDir, 'dist');

const appUrl = process.env.LANDING_APP_URL || 'https://app.procam.cloud';

if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

// Copy index.html
const indexHtml = fs.readFileSync(path.join(landingDir, 'index.html'), 'utf8');
fs.writeFileSync(path.join(outDir, 'index.html'), indexHtml, 'utf8');

// Write config.js with app URL
const configJs = `// Generated by landing build. App URL: ${appUrl}\nwindow.PROCAM_APP_URL = ${JSON.stringify(appUrl)};\n`;
fs.writeFileSync(path.join(outDir, 'config.js'), configJs, 'utf8');

console.log('Landing build done:', outDir);
console.log('App URL:', appUrl);
